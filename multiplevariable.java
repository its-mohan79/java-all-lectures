public class multiplevariable {
   public static void main(String[] args) {

int x = 5;
int y = 6;
int z = 50;
System.out.println(x + y + z); // 61


int x1 = 5, y1 = 6, z1 = 50;
System.out.println(x1 + y1 + z1); // 61



int x2, y2, z2;
x2 = y2 = z2 = 50;
System.out.println(x2 + y2 + z2); // 150







   }





    
}
