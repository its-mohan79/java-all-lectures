public class numbersdatatypes{
    public static void main(String[] args) {


byte Mynum = 120;
System.out.println(Mynum);


short myNum = 5000;
System.out.println("My number is: "+myNum);



int mNum = 100000;
System.out.println(mNum);

long yNum = 15000000000L;
System.out.println(yNum);





float kyNum = 5.75f;
System.out.println(kyNum);


double lyNum = 19.99d;
System.out.println(lyNum);
 

float f1 = 35e3f;
double d1 = 12E4d;
System.out.println(f1);
System.out.println(d1);




}
    
}
